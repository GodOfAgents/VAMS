"""Gateway evidence labels must describe the actual Envoy CI validation.

Every generated manifest below is a temporary local unit fixture with pending
results and synthetic Git state. It is never release evidence.
"""
from __future__ import annotations

import importlib.util
import json
import tempfile
import unittest
from pathlib import Path
from unittest import mock

MODULE_PATH = Path(__file__).with_name('audit_program.py')
SPEC = importlib.util.spec_from_file_location('gateway_command_audit_program', MODULE_PATH)
assert SPEC is not None and SPEC.loader is not None
audit_program = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(audit_program)

ENVOY_COMMAND = (
    'python scripts/security/validate_envoy_gateway.py && '
    '"$RUNNER_TEMP/envoy" --mode validate -c "$RUNNER_TEMP/envoy-ci/envoy.yaml"'
)
RETIRED_COMMAND = (
    'caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile && '
    'caddy adapt --config /etc/caddy/Caddyfile --adapter caddyfile --pretty'
)
FIXTURE_COMMIT = 'a' * 40


def synthetic_git(*arguments: str) -> str:
    if arguments == ('rev-parse', 'HEAD'):
        return FIXTURE_COMMIT
    if arguments == ('status', '--porcelain'):
        return ' M synthetic-unit-fixture\n'
    raise AssertionError('Unexpected Git query in local unit fixture')


class GatewayEvidenceCommandTests(unittest.TestCase):
    def _local_pending_fixture(self, directory: Path) -> tuple[Path, dict]:
        output = directory / 'LOCAL-PENDING-UNIT-FIXTURE.json'
        with (
            mock.patch.object(audit_program, '_git', side_effect=synthetic_git),
            mock.patch.object(audit_program, 'EVIDENCE_DIR', directory / 'no-artifacts'),
            mock.patch.dict(audit_program.os.environ, {}, clear=True),
        ):
            audit_program.generate_manifest(
                output,
                [f'{name}=pending' for name in sorted(audit_program.REQUIRED_EVIDENCE_RESULTS)],
            )
        data = json.loads(output.read_text())
        self.assertEqual(data['environment'], 'local')
        self.assertIs(data['dirty'], True)
        self.assertEqual(data['commit_sha'], FIXTURE_COMMIT)
        self.assertEqual(data['evidence_artifacts'], [])
        self.assertTrue(all(row['status'] == 'pending' for row in data['results']))
        self.assertEqual(
            {row['name'] for row in data['results']},
            set(audit_program.REQUIRED_EVIDENCE_RESULTS),
        )
        return output, data

    def _consumer_errors(self, directory: Path, command: str) -> list[str]:
        output, data = self._local_pending_fixture(directory)
        gateway = next(row for row in data['results'] if row['name'] == 'gateway-config')
        gateway['command'] = command
        output.write_text(json.dumps(data))
        signature = directory / 'NOT-A-SIGNATURE.unit-fixture'
        signature.write_text('nonempty unit fixture; no signature or signing claim')
        return audit_program._validate_evidence_manifest(output, signature, FIXTURE_COMMIT)

    def test_catalog_matches_actual_gateway_workflow_commands(self) -> None:
        workflow = (audit_program.ROOT / '.github/workflows/security-gates.yml').read_text()
        gateway = workflow.split('  gateway-config-gate:\n', 1)[1].split('  sbom-generation:\n', 1)[0]
        actual_lines = {line.strip() for line in gateway.splitlines()}
        for expected_line in ENVOY_COMMAND.split(' && '):
            self.assertIn(expected_line, actual_lines)
        self.assertEqual(audit_program.REQUIRED_EVIDENCE_RESULTS['gateway-config'], ENVOY_COMMAND)

    def test_generator_emits_envoy_label_in_local_pending_fixture(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            _, data = self._local_pending_fixture(Path(temporary))
        gateway = next(row for row in data['results'] if row['name'] == 'gateway-config')
        self.assertEqual(gateway['command'], ENVOY_COMMAND)

    def test_consumer_rejects_retired_caddy_label(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            errors = self._consumer_errors(Path(temporary), RETIRED_COMMAND)
        self.assertIn('evidence gate command mismatch: gateway-config', errors)

    def test_envoy_label_does_not_authorize_local_pending_evidence(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            errors = self._consumer_errors(Path(temporary), ENVOY_COMMAND)
        self.assertNotIn('evidence gate command mismatch: gateway-config', errors)
        self.assertIn('evidence gate did not pass: gateway-config', errors)
        self.assertIn('evidence manifest must be generated by GitHub Actions', errors)
        self.assertIn('evidence manifest was generated from a dirty tree', errors)

    def test_consumer_rejects_unreviewed_command_variant(self) -> None:
        with tempfile.TemporaryDirectory() as temporary:
            errors = self._consumer_errors(
                Path(temporary), ENVOY_COMMAND.replace('--mode validate', '--mode serve')
            )
        self.assertIn('evidence gate command mismatch: gateway-config', errors)


if __name__ == '__main__':
    unittest.main()
